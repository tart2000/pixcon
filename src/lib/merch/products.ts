  product.catalog.colors.find((c) => c.name.toLowerCase() === name?.toLowerCase());

/** French VAT rate: catalog costs are before VAT, shop prices include it. */
export const VAT = 0.2;

/** With French VAT, rounded to the cent. */
export const withVat = (amount: number) => Math.round(amount * (1 + VAT) * 100) / 100;

/**
 * Price of a size in euros, VAT included: the base price, plus what the size costs us more than
 * the cheapest one (with VAT), rounded up to the euro.
 */
export function priceOf(product: Product, cost: number) {
  const min = Math.min(...product.catalog.colors.flatMap((c) => c.sizes.map((s) => s.cost)));
  return product.basePrice + Math.ceil(withVat(cost - min));
}

export const isStyle = (s: string | null | undefined): s is StyleId => STYLES.some((x) => x.id === s);
export const isVariant = (v: string | null | undefined): v is Variant => VARIANTS.some((x) => x.id === v);

/**
 * The print file's layout, in its pixels: the print area at the resolution Printful expects
 * (`width` × `height`), and the icon's square (`x`, `y`, `side`) on it.
 */
export function printLayout(product: Product) {
  const { width, height, dpi } = product.catalog.printArea;
  const side = product.design.width * dpi;
  return { width: width * dpi, height: height * dpi, x: ((width - product.design.width) / 2) * dpi, y: product.design.top * dpi, side };
}

/** The print file as an SVG: the whole print area, transparent, with the icon placed on it. */
export function printSvg(product: Product, pixels: string, style: StyleId, ink: string) {
  const { width, height, x, y, side } = printLayout(product);
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">` +
    `<svg x="${x}" y="${y}" width="${side}" height="${side}" viewBox="0 0 110 110" fill="${ink}">` +
    `<path d="${iconPath(decode(pixels), style)}"/></svg></svg>`
  );
}

/** URL of a design's print file (see app/api/merch/print). */
export const printUrl = (d: { product: string; icon: string; style: StyleId; variant: Variant; ink: string }) =>
  `/api/merch/print?${new URLSearchParams({ product: d.product, icon: d.icon, style: d.style, variant: d.variant, ink: d.ink.slice(1) })}`;
